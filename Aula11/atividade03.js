// Exercício: cálculo da área de um quadrado

// Entrada: leitura do lado do quadrado
let lado = parseFloat(prompt("Digite o valor do lado do quadrado:"));

// Processamento: cálculo da área (lado * lado)
let area = lado * lado;

// Saída: mostrar a área
console.log("O lado do quadrado é: " + lado);
console.log("A área do quadrado é: " + area);
