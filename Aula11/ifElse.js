//if else é utilizado quando temos duas possibilidades, sendo que quando uma não é verdade a outra é obrigatoriamente verdade. Exemplo: se o número é par, então ele não é ímpar, e vice-versa.

//impar / par
//positivo / negativo
//aprovado / reprovado
//verdadeiro / falso
let num1 = 10
let num2 = 20

if (num1 > num2) {
    console.log("O número 1 é maior que o número 2.")
} else {
    //caso condição do if seja falsa, o código dentro do else será executado
    console.log("O número 1 não é maior que o número 2.")
}   